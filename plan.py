def stage_by_id(sid):
    for s in STAGES:
        if s["id"] == sid:
            return s
    return None


def dimension(key):
    for d in DIMENSIONS:
        if d["key"] == key:
            return d
    return None


def dimension_target(key):
    """该维度在各阶段里最高的那条验收线，用于页面上显示“目标 ≥ X”。"""
    tgt = None
    for s in STAGES:
        v = s["pass"].get(key)
        if v is not None and (tgt is None or v > tgt):
            tgt = v
    return tgt


def evaluate(dims):
    """按 dims 判断每个阶段的达标情况，并给出“现在该主攻哪一阶段”。

    以前的做法是「找到第一个没全过的阶段就当当前阶段」，有两个毛病：

    1. **后面阶段的进度完全看不见**。旧数据里 19 条有 14 条卡在第二阶段，
       全是 flow 拖的；哪怕第三、四阶段的条件早就满足了，页面上也只显示
       第二阶段，用户会以为自己一点没进步。
    2. **一条录音就能整体倒退**。dims 只取最近一条，偶然录差一次就退回第一阶段。

    现在：
    - 每个阶段独立判定，各自给出 pass/fail 和差哪一项；
    - 主攻阶段取「最靠前的未达标阶段」，但已达标的后面的阶段仍然标为已达标；
    - ready/weak 按各维度自己的最高验收线算，不再硬编码 70
      （原来 breath 的线是 70、clarity 是 82，却统一拿 70 当“好/差”的分界）。
    """
    stage_rows = []
    first_unmet = None
    for s in STAGES:
        missing = []
        for k, t in s["pass"].items():
            v = dims.get(k)
            if v is None or v < t:
                missing.append({"key": k, "value": v, "target": t})
        ok = not missing
        if not ok and first_unmet is None:
            first_unmet = s
        stage_rows.append({
            "id": s["id"],
            "name": s["name"],
            "passed": ok,
            "missing": missing,
        })

    ready, weak = [], []
    for d in DIMENSIONS:
        v = dims.get(d["key"])
        if v is None:
            continue
        tgt = dimension_target(d["key"])
        if tgt is None or v >= tgt:
            ready.append(d["key"])
        else:
            weak.append(d["key"])

    return {
        "stage": first_unmet["id"] if first_unmet else None,
        "stage_name": first_unmet["name"] if first_unmet else "四阶段已全部达标",
        # 每个阶段的独立结论，页面上可以逐阶段显示“已达标记”
        "stages": stage_rows,
        # 已完全达标的阶段（可能不是前缀：比如第一没过但第三过了）
        "stages_passed": [r["id"] for r in stage_rows if r["passed"]],
        "ready": ready,
        "weak": weak,
        "all_done": first_unmet is None,
    }
