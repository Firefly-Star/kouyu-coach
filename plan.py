def stage_by_id(sid):
    for s in STAGES:
        if s["id"] == sid:
            return s
    return None


def dimension(key):
    for d in DIMENSIONS:
        if d["key"] == key:
            return d
    return None


def evaluate(dims):
    """按 dims 判断当前处在哪个阶段、哪些维度已达标。

    返回：{stage: 建议主攻阶段, ready: 已达标维度, weak: 待补维度, done: 全部通过}
    """
    ready, weak = [], []
    for d in DIMENSIONS:
        v = dims.get(d["key"])
        if v is None:
            continue
        (ready if v >= 70 else weak).append(d["key"])
    # 找到第一个还没全过的阶段
    cur = None
    for s in STAGES:
        ok = all((dims.get(k) or 0) >= t for k, t in s["pass"].items())
        if not ok:
            cur = s
            break
    return {
        "stage": cur["id"] if cur else None,
        "stage_name": cur["name"] if cur else "四阶段已全部达标",
        "ready": ready,
        "weak": weak,
        "all_done": cur is None,
    }
