def todays_topic(day_index):
    """按天取一条「每日一题」。

    用天序号取模而不是随机：同一天多次打开拿到的是同一题（可以反复练到满意），
    第二天自然换成下一题。这比每次随机更容易形成"今天练这个"的仪式感。
    """
    if not ALL_TOPICS:
        return None
    return ALL_TOPICS[day_index % len(ALL_TOPICS)]
